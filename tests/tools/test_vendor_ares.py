"""Offline tests for tools/vendor/vendor_ares.py. The fixture repo is local,
so no network is used."""
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "tools" / "vendor" / "vendor_ares.py"
PIN = ROOT / "tools" / "vendor" / "ares.json"
# Fixture commits must not depend on the developer's git config.
GIT_ENV = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull,
           "GIT_CONFIG_NOSYSTEM": "1",
           "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.invalid",
           "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.invalid"}


def sh(cwd, *args):
    return subprocess.run(["git", "-C", str(cwd), *args], check=True,
                          capture_output=True, text=True,
                          env=GIT_ENV).stdout.strip()


def make_repo(test, files, links=None):
    """Create a local upstream repo with one commit. Returns (path, commit)."""
    tmp = Path(tempfile.mkdtemp())
    test.addCleanup(shutil.rmtree, tmp)
    repo = tmp / "src"
    sh(tmp, "init", "-q", "-b", "main", str(repo))
    for path, data in files.items():
        p = repo / path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(data)
    for path, target in (links or {}).items():
        p = repo / path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.symlink_to(target)
    sh(repo, "add", "-A")
    sh(repo, "commit", "-qm", "fixture")
    # Let the script fetch this exact SHA from a non-bare local repo.
    sh(repo, "config", "uploadpack.allowAnySHA1InWant", "true")
    return repo, sh(repo, "rev-parse", "HEAD")


def make_pin(tmp, repo, commit, paths):
    pin = tmp / "pin.json"
    pin.write_text(json.dumps({"repo": repo.as_uri(), "commit": commit,
                               "paths": paths}))
    return pin


def run(pin, dest):
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--pin", str(pin), "--dest", str(dest)],
        capture_output=True, text=True)


class VendorAresTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)

    def test_vendors_listed_paths_and_manifest(self):
        repo, commit = make_repo(self, {
            "LICENSE": "ISC\n",
            "ares/sfc/a.cpp": "a\n",
            "nall/b.hpp": "b\n",
            "extra/skip.txt": "skip\n",
        })
        pin = make_pin(self.tmp, repo, commit,
                       ["LICENSE", "ares/sfc", "nall"])
        dest = self.tmp / "out"

        first = run(pin, dest)
        self.assertEqual(first.returncode, 0, first.stderr)
        self.assertEqual(
            first.stdout.strip(),
            f"vendored ares {commit} into {dest} (3 files)")
        self.assertEqual((dest / "ares/sfc/a.cpp").read_text(), "a\n")
        self.assertEqual((dest / "nall/b.hpp").read_text(), "b\n")
        self.assertFalse((dest / "extra").exists())
        self.assertEqual((dest / "VENDORED.txt").read_text(),
                         f"repo: {repo.as_uri()}\n"
                         f"commit: {commit}\n"
                         "paths: LICENSE ares/sfc nall\n"
                         "Generated by tools/vendor/vendor_ares.py. Do not "
                         "edit files here; local changes go in "
                         "patches/ares/.\n")

        # A re-run replaces the destination instead of merging into it.
        (dest / "stale.txt").write_text("stale\n")
        second = run(pin, dest)
        self.assertEqual(second.returncode, 0, second.stderr)
        self.assertFalse((dest / "stale.txt").exists())

    def test_rejects_bad_pin(self):
        repo, commit = make_repo(self, {"LICENSE": "ISC\n"})
        cases = [
            ("abc", ["LICENSE"]),                      # short commit
            ("A" * 40, ["LICENSE"]),                   # uppercase
            (commit, ["../escape"]),                   # traversal
            (commit, ["/etc/passwd"]),                 # absolute
            (commit, [".git"]),                        # git metadata
            (commit, []),                              # empty paths
            (commit, ["LICENSE", "LICENSE"]),          # duplicate
        ]
        for bad_commit, paths in cases:
            with self.subTest(commit=bad_commit, paths=paths):
                pin = make_pin(self.tmp, repo, bad_commit, paths)
                result = run(pin, self.tmp / "out")
                self.assertEqual(result.returncode, 1)
                self.assertIn("error:", result.stderr)

    def test_missing_path_fails_before_touching_dest(self):
        repo, commit = make_repo(self, {"LICENSE": "ISC\n"})
        pin = make_pin(self.tmp, repo, commit, ["LICENSE", "missing"])
        dest = self.tmp / "out"
        dest.mkdir()
        (dest / "keep.txt").write_text("keep\n")

        result = run(pin, dest)

        self.assertEqual(result.returncode, 1)
        self.assertIn("missing", result.stderr)
        self.assertEqual((dest / "keep.txt").read_text(), "keep\n")

    def test_symlink_fails_before_touching_dest(self):
        repo, commit = make_repo(
            self, {"LICENSE": "ISC\n", "ares/sfc/a.cpp": "a\n"},
            {"ares/sfc/link": "a.cpp"})
        pin = make_pin(self.tmp, repo, commit, ["ares/sfc"])
        dest = self.tmp / "out"
        dest.mkdir()
        (dest / "keep.txt").write_text("keep\n")

        result = run(pin, dest)

        self.assertEqual(result.returncode, 1)
        self.assertIn("symlink", result.stderr)
        self.assertEqual((dest / "keep.txt").read_text(), "keep\n")

    def test_rejects_dangerous_destinations(self):
        spec = importlib.util.spec_from_file_location("vendor_ares_under_test",
                                                      SCRIPT)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)

        repo_root = self.tmp / "repo"
        repo_root.mkdir()
        pin = repo_root / "pin.json"
        protected = [repo_root, pin, Path.home()]
        for dest in (Path("/"), Path.home(), repo_root, self.tmp):
            with self.subTest(dest=dest):
                with self.assertRaises(ValueError):
                    module.resolve_destination(dest, protected)

        dest = self.tmp / "out"
        self.assertEqual(module.resolve_destination(dest, protected),
                         dest.resolve())

        # The source checkout is created inside a temp dir; neither the
        # checkout, its children, nor a directory containing it are safe.
        source_root = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, source_root)
        source = source_root / "checkout"
        source.mkdir()
        for dest in (source, source / "nested", source_root):
            with self.subTest(source_dest=dest):
                with self.assertRaises(ValueError):
                    module.resolve_destination(dest, protected, [source])

    def test_pin_names_the_card_paths_at_a_full_commit(self):
        pin = json.loads(PIN.read_text())
        self.assertEqual(pin["repo"],
                         "https://github.com/ares-emulator/ares.git")
        self.assertRegex(pin["commit"], r"\A[0-9a-f]{40}\Z")
        self.assertEqual(pin["paths"], ["LICENSE", "ares/ares",
                                        "ares/component", "ares/sfc",
                                        "nall", "libco",
                                        "thirdparty/sljit/sljit_src",
                                        "thirdparty/sljit/LICENSE",
                                        "thirdparty/sljit.h",
                                        "thirdparty/sljitConfigPre.h",
                                        "thirdparty/sljitConfigPost.h"])


if __name__ == "__main__":
    unittest.main()
